export function translateCharacterSubclassName(value, language = "es") {
  const name = String(value ?? "").trim();
  if (!name || language === "en") {
    return name;
  }

  return SPANISH_SUBCLASS_NAMES[name] ?? name;
}

export function isCharacterSubclassNameMatch(subclass, value) {
  const requested = normalize(value);
  if (!requested) {
    return false;
  }

  return [subclass?.name, subclass?.shortName]
    .filter(Boolean)
    .some((name) => (
      normalize(name) === requested
      || normalize(translateCharacterSubclassName(name, "es")) === requested
    ));
}

function normalize(value) {
  return String(value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim();
}
